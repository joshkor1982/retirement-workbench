#!/usr/bin/env python3
"""Generate statetax_data.go from Tax Foundation's state income tax table.

Download the workbook, then run from the repo root:

    curl -sLo /tmp/tf.xlsx https://taxfoundation.org/wp-content/uploads/2026/02/2026-State-Individual-Income-Tax-Rates-Brackets.xlsx
    python3 scripts/statetax/gen.py /tmp/tf.xlsx 2026 > statetax_data.go && gofmt -w statetax_data.go

It reads the first sheet (the newest year): rates and brackets for single
and joint filers, the standard deduction, and the personal exemption, which
some states give as a credit instead. Standard library only.
"""
import re, sys, zipfile, xml.etree.ElementTree as ET

NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
ABBR = {"Ala.": "AL", "Alaska": "AK", "Ariz.": "AZ", "Ark.": "AR", "Calif.": "CA", "Colo.": "CO", "Conn.": "CT",
        "Del.": "DE", "Fla.": "FL", "Ga.": "GA", "Hawaii": "HI", "Idaho": "ID", "Ill.": "IL", "Ind.": "IN",
        "Iowa": "IA", "Kans.": "KS", "Ky.": "KY", "La.": "LA", "Maine": "ME", "Md.": "MD", "Mass.": "MA",
        "Mich.": "MI", "Minn.": "MN", "Miss.": "MS", "Mo.": "MO", "Mont.": "MT", "Nebr.": "NE", "Nev.": "NV",
        "N.H.": "NH", "N.J.": "NJ", "N.M.": "NM", "N.Y.": "NY", "N.C.": "NC", "N.D.": "ND", "Ohio": "OH",
        "Okla.": "OK", "Ore.": "OR", "Pa.": "PA", "R.I.": "RI", "S.C.": "SC", "S.D.": "SD", "Tenn.": "TN",
        "Tex.": "TX", "Utah": "UT", "Vt.": "VT", "Va.": "VA", "Wash.": "WA", "W.Va.": "WV", "Wis.": "WI",
        "Wyo.": "WY", "D.C.": "DC"}


def rows(path):
    z = zipfile.ZipFile(path)
    ss = []
    if "xl/sharedStrings.xml" in z.namelist():
        for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS):
            ss.append("".join(t.text or "" for t in si.iter("{%s}t" % NS["m"])))
    sheet = ET.fromstring(z.read("xl/worksheets/sheet1.xml"))
    for r in sheet.iter("{%s}row" % NS["m"]):
        row = {}
        for c in r.findall("m:c", NS):
            col = re.match(r"[A-Z]+", c.get("r")).group()
            v, inline = c.find("m:v", NS), c.find("m:is", NS)
            if v is not None:
                row[col] = ss[int(v.text)] if c.get("t") == "s" else v.text
            elif inline is not None:
                row[col] = "".join(t.text or "" for t in inline.iter("{%s}t" % NS["m"]))
        yield {k: v.replace("\xa0", " ").strip() for k, v in row.items()}


def state(a):
    for k in sorted(ABBR, key=len, reverse=True):
        if a == k or a.startswith(k + " ") or a.startswith(k + "("):
            return ABBR[k]
    return None


def amount(s):
    """Returns (deduction, credit) in whole dollars from '3000' or '$29 credit'."""
    s = (s or "").strip()
    m = re.fullmatch(r"\$?([\d,]+)( credit)?", s)
    if not m:
        return 0, 0
    n = int(m.group(1).replace(",", ""))
    return (0, n) if m.group(2) else (n, 0)


def main(path, year):
    out, cur = {}, None
    for r in rows(path):
        s = state(r.get("A", ""))
        if s:
            cur = s
            out[s] = {"sd": (r.get("H"), r.get("I")), "pe": (r.get("J"), r.get("K")), "s": [], "j": [], "none": False}
        if not cur:
            continue
        rate = r.get("B", "")
        if rate.lower() in ("none", "capital gains income only"):
            out[cur]["none"] = True
        num = lambda k: re.fullmatch(r"[\d.E+-]+", r.get(k, "")) is not None
        if num("B") and num("D"):  # single and joint columns can run to different lengths
            out[cur]["s"].append((int(float(r["D"])), float(r["B"])))
        if num("E") and num("G"):
            out[cur]["j"].append((int(float(r["G"])), float(r["E"])))
        if len(out) == 51 and cur == "DC" and not r:
            break
    assert len(out) == 51, len(out)
    print("// Code generated by scripts/statetax/gen.py from Tax Foundation,")
    print(f'// "State Individual Income Tax Rates and Brackets, {year}". DO NOT EDIT.')
    print("\npackage main\n")
    print(f"const stateTaxYear = {year}\n")
    print("var stateTaxes = map[string]stateTax{")
    for s, v in sorted(out.items()):
        if v["none"]:
            print(f'\t"{s}": {{NoTax: true}},')
            continue
        sdS, crS1 = amount(v["sd"][0]); sdJ, crJ1 = amount(v["sd"][1])
        exS, crS2 = amount(v["pe"][0]); exJ, crJ2 = amount(v["pe"][1])
        single = ", ".join(f"{{{o}, {r!r}}}" for o, r in v["s"])
        joint = ", ".join(f"{{{o}, {r!r}}}" for o, r in v["j"])
        print(f'\t"{s}": {{Single: []bracket{{{single}}}, Joint: []bracket{{{joint}}},')
        print(f"\t\tStdS: {sdS}, StdJ: {sdJ}, ExS: {exS}, ExJ: {exJ}, CrS: {crS1 + crS2}, CrJ: {crJ1 + crJ2}}},")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
